<script>
    // Fungsi untuk mengkonversi VAPID KEY dari Base64 ke Uint8Array
    function urlBase64ToUint8Array(base64String) {
        const padding = '='.repeat((4 - base64String.length % 4) % 4);
        const base64 = (base64String + padding).replace(/\-/g, '+').replace(/_/g, '/');
        const rawData = window.atob(base64);
        const outputArray = new Uint8Array(rawData.length);
        for (let i = 0; i < rawData.length; ++i) {
            outputArray[i] = rawData.charCodeAt(i);
        }
        return outputArray;
    }

    // Fungsi untuk mendaftarkan device ke Laravel
    function subscribeUserToPush() {
        navigator.serviceWorker.ready.then((registration) => {
            const vapidPublicKey = "{{ env('VAPID_PUBLIC_KEY') }}";
            
            // Jika VAPID key belum ada di .env, hentikan proses
            if (!vapidPublicKey) {
                console.error("VAPID_PUBLIC_KEY belum di-set di file .env");
                return;
            }

            const convertedVapidKey = urlBase64ToUint8Array(vapidPublicKey);

            registration.pushManager.subscribe({
                userVisibleOnly: true,
                applicationServerKey: convertedVapidKey
            }).then((subscription) => {
                // Tembak data subscription ke endpoint Laravel yang sudah Anda buat
                fetch('/push-subscribe', {
                    method: 'POST',
                    headers: {
                        'Content-Type': 'application/json',
                        'X-CSRF-TOKEN': '{{ csrf_token() }}'
                    },
                    body: JSON.stringify(subscription)
                }).then(response => response.json())
                  .then(data => console.log('Perangkat berhasil didaftarkan ke PWA:', data))
                  .catch(err => console.error('Gagal mengirim ke database:', err));
            }).catch(err => console.error('Gagal subscribe Push Manager:', err));
        });
    }

    // Minta izin ke user saat halaman dimuat
    if ('serviceWorker' in navigator && 'PushManager' in window) {
        navigator.serviceWorker.register('/sw.js').then(() => {
            if (Notification.permission === 'default') {
                Notification.requestPermission().then((permission) => {
                    if (permission === 'granted') {
                        subscribeUserToPush();
                    }
                });
            } else if (Notification.permission === 'granted') {
                // Jika sebelumnya sudah diizinkan, pastikan token selalu update
                subscribeUserToPush();
            }
        });
    }
</script>
